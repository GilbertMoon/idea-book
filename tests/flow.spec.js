import {test,expect} from '@playwright/test'
const base=`http://127.0.0.1:${process.env.E2E_PORT || 5188}`
async function addTeam(page,name='가조') {
 await page.getByPlaceholder('조 이름 (예: 1조, 2조...)').fill(name)
 await page.getByRole('button',{name:'조 추가',exact:true}).click()
}
async function prepare(page){await page.getByRole('button',{name:'경기 준비',exact:true}).click();await expect(page.getByRole('button',{name:'출발',exact:true})).toBeVisible()}
test('준비 중 공 고정·장애물 동작, 실제 출발·세 구간·재경기',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto(base); await addTeam(page); await addTeam(page,'나조')
 await prepare(page)
 const canvas=page.locator('canvas')
 await expect(canvas).toHaveAttribute('data-status','READY')
 const ready=await page.locator('.team-progress').evaluateAll(rows=>rows.map(r=>[r.dataset.x,r.dataset.y]))
 const animation=await canvas.getAttribute('data-animation')
 await expect.poll(()=>canvas.getAttribute('data-animation')).not.toBe(animation)
 expect(await page.locator('.team-progress').evaluateAll(rows=>rows.map(r=>[r.dataset.x,r.dataset.y]))).toEqual(ready)
 await expect(page.locator('.race-clock')).toHaveText('0.00초')
 await page.getByRole('button',{name:'출발',exact:true}).click()
 await expect(canvas).toHaveAttribute('data-status','RUNNING')
 await expect(page.getByRole('button',{name:'출발',exact:true})).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'🎉 발표 순서 확정!'})).toBeVisible({timeout:110000})
 await expect(page.locator('.ranking-row')).toHaveCount(2)
 await page.getByRole('button',{name:'다시 경기하기',exact:true}).click()
 await expect(canvas).toHaveAttribute('data-status','READY')
 await expect(page.locator('.team-progress')).toHaveCount(2)
 await page.getByRole('button',{name:'관리자 설정',exact:true}).click()
 await expect(page.locator('.group-card')).toHaveCount(2)
 expect(errors).toEqual([])
})
test('팀·사진·난이도 저장, 새로고침·재경기 후 보존',async({page})=>{
 await page.goto(base);await addTeam(page,'사진조')
 const card=page.locator('.group-card')
 await card.getByRole('button',{name:'▼'}).click()
 await card.getByPlaceholder('조원 이름').fill('조원')
 const chooserPromise=page.waitForEvent('filechooser');await card.getByRole('button',{name:'사진 추가 +',exact:true}).click(); const chooser=await chooserPromise; await chooser.setFiles({name:'photo.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" fill="orange"/></svg>')})
 await expect(card.locator('.member-avatar')).toBeVisible()
 await page.getByLabel('난이도',{exact:true}).selectOption('hard')
 await expect(page.getByRole('status').filter({hasText:'이 브라우저에 저장됨'})).toBeVisible()
 await page.reload()
 await expect(page.locator('.group-card')).toHaveCount(1)
 await expect(page.getByLabel('난이도',{exact:true})).toHaveValue('hard')
 await page.locator('.group-card').getByRole('button',{name:'▼'}).click()
 const img=page.locator('.member-avatar')
 await expect(img).toBeVisible()
 expect(await img.evaluate(el=>el.complete&&el.naturalWidth>0)).toBe(true)
 await prepare(page)
 await expect(page.locator('.team-progress img')).toBeVisible()
})
test('Slack 명시적 저장·마스킹·복원·자동 실패·수동 재전송',async({page})=>{
 let count=0
 await page.route('https://hooks.slack.com/services/test-only',async route=>{count++;await route.fulfill({status:count===1?500:200,body:count===1?'failure':'ok',headers:{'Access-Control-Allow-Origin':'*'}})})
 await page.goto(base);await addTeam(page,'전송조')
 await page.getByLabel('Slack 웹훅 URL',{exact:true}).fill('https://hooks.slack.com/services/test-only')
 await page.getByLabel('이 브라우저에 저장',{exact:true}).check()
 await expect(page.getByRole('status').filter({hasText:'이 브라우저에 저장됨'})).toBeVisible()
 await page.reload()
 await expect(page.getByLabel('Slack 웹훅 URL',{exact:true})).toHaveAttribute('type','password')
 await expect(page.getByLabel('Slack 웹훅 URL',{exact:true})).toHaveValue('https://hooks.slack.com/services/test-only')
 await page.getByLabel('경기 제한시간 (초)',{exact:true}).fill('2')
 await prepare(page);await page.getByRole('button',{name:'출발',exact:true}).click()
 await expect(page.locator('.slack-status.error')).toBeVisible({timeout:15000})
 expect(count).toBe(1)
 await page.getByRole('button',{name:'Slack 재전송',exact:true}).click()
 await expect(page.locator('.slack-status.success')).toBeVisible()
 expect(count).toBe(2)
 await expect(page.locator('.ranking-row')).toContainText('DNF')
})
