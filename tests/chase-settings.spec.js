import {test,expect} from '@playwright/test'
test('legacy settings migrate; attack edits persist and resetting only attacks retains other data',async({page})=>{
 await page.goto(`http://127.0.0.1:${process.env.E2E_PORT || 5188}/`)
 await expect(page.locator('.save-status')).toHaveText('이 브라우저에 저장됨')
 await page.evaluate(async()=>{
  const {StorageService}=await import('/src/services/StorageService.js');const storage=new StorageService()
  await storage.save({groups:[{id:'team',name:'Preserved',members:[{id:'member',name:'Photo',photoBlob:new Blob(['<svg xmlns="http://www.w3.org/2000/svg" width="8" height="8"><rect width="8" height="8" fill="red"/></svg>'],{type:'image/svg+xml'})}]}],settings:{difficulty:'hard',maxReturns:3,maxRaceSeconds:123},slackSettings:{url:'https://hooks.slack.com/services/test-only',remember:true},obstacleSettings:{fixed:[],rotating:[],oscillating:[]},isShuffled:true});storage.close()
 });await page.reload()
 await expect(page.getByLabel('대포 공격',{exact:true})).toBeChecked()
 await expect(page.getByLabel('공격 거리 (공 지름 배수)',{exact:true})).toHaveValue('3')
 await page.getByLabel('낚싯대 공격',{exact:true}).check()
 await page.getByLabel('공격 거리 (공 지름 배수)',{exact:true}).fill('5')
 await page.getByLabel('공격 충격량 (px/s)',{exact:true}).fill('210')
 await page.getByLabel('공격 쿨다운 (초)',{exact:true}).fill('12')
 await page.getByLabel('최대 공격 횟수',{exact:true}).fill('4')
 await page.getByLabel('피격 보호시간 (초)',{exact:true}).fill('3')
 await page.getByLabel('공격 효과 연출',{exact:true}).uncheck()
 await expect(page.locator('.save-status')).toHaveText('이 브라우저에 저장됨')
 await page.reload()
 await expect(page.getByLabel('공격 거리 (공 지름 배수)',{exact:true})).toHaveValue('5')
 await expect(page.getByLabel('공격 충격량 (px/s)',{exact:true})).toHaveValue('210')
 await expect(page.getByLabel('공격 쿨다운 (초)',{exact:true})).toHaveValue('12')
 await expect(page.getByLabel('최대 공격 횟수',{exact:true})).toHaveValue('4')
 await expect(page.getByLabel('피격 보호시간 (초)',{exact:true})).toHaveValue('3')
 await expect(page.getByLabel('낚싯대 공격',{exact:true})).toBeChecked()
 await expect(page.getByLabel('공격 효과 연출',{exact:true})).not.toBeChecked()
 await page.getByLabel('공격 사용 안 함',{exact:true}).check()
 await expect(page.locator('.save-status')).toHaveText('이 브라우저에 저장됨')
 await page.reload()
 await expect(page.getByLabel('공격 사용 안 함',{exact:true})).toBeChecked()
 await page.getByRole('button',{name:'공격 설정 초기화',exact:true}).click()
 await expect(page.locator('.save-status')).toHaveText('이 브라우저에 저장됨')
 await page.reload()
 await expect(page.getByLabel('대포 공격',{exact:true})).toBeChecked()
 await expect(page.getByLabel('공격 효과 연출',{exact:true})).toBeChecked()
 await page.getByLabel('낚싯대 공격',{exact:true}).check()
 await expect(page.getByLabel('공격 충격량 (px/s)',{exact:true})).toHaveValue('180')
 await page.getByLabel('대포 공격',{exact:true}).check()
 await expect(page.locator('.save-status')).toHaveText('이 브라우저에 저장됨')
 const retained=await page.evaluate(async()=>{const {StorageService}=await import('/src/services/StorageService.js');const s=new StorageService();const data=await s.load();s.close();return {team:data.groups[0].name,photo:await data.groups[0].members[0].photoBlob.text(),difficulty:data.settings.difficulty,maxRaceSeconds:data.settings.maxRaceSeconds,slack:data.slackSettings,isShuffled:data.isShuffled,chase:data.settings.chaseAttack}})
 expect(retained.team).toBe('Preserved');expect(retained.photo).toContain('<svg');expect(retained.difficulty).toBe('hard');expect(retained.maxRaceSeconds).toBe(123);expect(retained.slack.remember).toBe(true);expect(retained.slack.url).toBe('https://hooks.slack.com/services/test-only');expect(retained.isShuffled).toBe(true)
 expect(retained.chase).toMatchObject({enabled:true,rangeMultiplier:3,impulse:180,cooldown:8,maxAttacks:2,hitProtection:2,animationEnabled:true})
})
